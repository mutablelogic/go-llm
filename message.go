package llm

import (
	"encoding/json"
)

////////////////////////////////////////////////////////////////////////////////
// TYPES

// Message is a message in a conversation with a model, which providers
// convert to their own formats
type Message interface {
	Role() string              // Message role: user, assistant, system, thinking or tool
	Text() string              // Text content of the message
	Resources() []Resource     // Resources in the message, such as images or documents
	ToolCalls() []ToolCall     // Tools the model called, in a message from the model
	ToolResults() []ToolResult // Results of the tools the model called, in a tool message
}

// ToolCall is a call by a model to a tool
type ToolCall struct {
	ID    string          // Identifier of the call, which its result refers to
	Name  string          // Name of the tool the model called it by
	Input json.RawMessage // Input to the tool as JSON, which may be empty
}

// ToolResult is the result of a call by a model to a tool
type ToolResult struct {
	ID      string          // Identifier of the call
	Name    string          // Name of the tool the model called it by
	Content json.RawMessage // Result of the tool as JSON
	IsError bool            // Whether the result is an error
}

// Usage is the number of tokens used generating a message, or the pages
// recognized, or seconds of audio transcribed, for providers which charge
// by them. The cached and
// reasoning tokens are part of the input and output tokens, for providers
// which report them.
type Usage struct {
	InputTokens     uint `json:"input_tokens" help:"Tokens in the messages sent to the model" example:"26"`
	OutputTokens    uint `json:"output_tokens,omitempty" help:"Tokens in the message generated by the model" example:"12"`
	CachedTokens    uint `json:"cached_tokens,omitempty" help:"Of the input tokens, those read from the provider's cache" example:"0"`
	ReasoningTokens uint `json:"reasoning_tokens,omitempty" help:"Of the output tokens, those of reasoning which isn't returned" example:"0"`
	Pages           uint `json:"pages,omitempty" help:"Pages of documents and images whose text was recognized" example:"0"`
	Seconds         uint `json:"seconds,omitempty" help:"Seconds of audio transcribed, or translated, for providers which charge by the second" example:"0"`
}
